ENHANCE_PARAMS = '{"p_low":5, "p_high":95, "suppress_noise":true, "noise_threshold":"auto"}'


@dataclass(frozen=True)
class StepPlan:
    name: str
    command: list[str]
    outputs: tuple[Path, ...] = ()

    def command_text(self) -> str:
        return shlex.join(self.command)


def build_step_plans(
    row: dict[str, str],
    config: dict[str, Any] | None = None,
    *,
    include_downstream: bool = True,
    validate_fastq: bool = False,
    allow_missing_fastq: bool = True,
) -> list[StepPlan]:
    row = normalize_job_row(row)
    config = build_effective_config(row, config or {})
    workflow = normalize_workflow(row.get("workflow", ""))
    pipeline = normalize_pipeline(row.get("pipeline"))
    paths = resolve_runtime_paths(row, config)
    values = _values(row, config, workflow, paths)

    if pipeline == "report":
        return _report_steps(paths, values)
    if pipeline == "reanalysis":
        return _build_reanalysis_steps(paths, values, include_downstream=include_downstream)
    return _build_upstream_steps(row, config, paths, values, include_downstream, validate_fastq, allow_missing_fastq)


def filter_step_plans(
    plans: list[StepPlan],
    *,
    from_step: str | None = None,
    to_step: str | None = None,
    only_steps: str | list[str] | tuple[str, ...] | None = None,
) -> list[StepPlan]:
    """Filter generated step plans by stable step name selectors."""

    if only_steps:
        selectors = _normalize_step_selectors(only_steps)
        missing = [selector for selector in selectors if not any(_step_matches(plan.name, selector) for plan in plans)]
        if missing:
            raise ValueError(f"Step selector not found: {', '.join(missing)}")
        return [plan for plan in plans if any(_step_matches(plan.name, selector) for selector in selectors)]

    start_index = _selector_index(plans, from_step, default=0)
    end_index = _selector_index(plans, to_step, default=len(plans) - 1)
    if start_index > end_index:
        return []
    return plans[start_index : end_index + 1]


def _build_upstream_steps(
    row: dict[str, str],
    config: dict[str, Any],
    paths: RuntimePaths,
    values: dict[str, Any],
    include_downstream: bool,
    validate_fastq: bool,
    allow_missing_fastq: bool,
) -> list[StepPlan]:
    try:
        fastqs = detect_job_fastqs(row, config, validate_files=validate_fastq)
    except FileNotFoundError:
        if not allow_missing_fastq:
            raise
        fastqs = _planned_fastqs(paths)
    assert fastqs is not None

    sample = paths.sample
    sampledir = paths.sampledir
    genome = str(paths.genome_dir)
    thread = str(values["thread"])
    barcode_r2 = sampledir / "01.barcode" / f"{sample}_2.fq.gz"
    cutadapt_r2 = sampledir / "02.cutadapt" / f"{sample}_clean_2.fq.gz"
    star_bam = sampledir / "03.star" / f"{sample}_Aligned.sortedByCoord.out.bam"
    featurecounts_bam = sampledir / "04.featureCounts" / f"{sample}_nameSorted.bam"
    count_detail = sampledir / "05.count" / f"{sample}_count_detail.txt"

    count_outputs: tuple[Path, ...] = (count_detail,)
    if paths.mode == "scrna":
        # The scRNA analysis step consumes the filtered matrix generated by
        # count. Declare it as a planned output so execution preflight knows
        # it will exist after 05.count instead of requiring it beforehand.
        count_outputs += (
            sampledir / "05.count" / f"{sample}_filtered_feature_bc_matrix",
        )

    steps = [
        StepPlan(
            "00.sample",
            [
                "celatlas_spatial",
                "rna",
                "sample",
                "--outdir",
                str(sampledir / "00.sample"),
                "--sample",
                sample,
                "--thread",
                thread,
                "--chemistry",
                paths.chemistry,
                "--fq1",
                str(fastqs.sample_fq1),
            ],
            outputs=(sampledir / "00.sample" / "step.log",),
        ),
        StepPlan(
            "01.barcode",
            _barcode_command(paths, values, fastqs.fq1_csv, fastqs.fq2_csv),
            outputs=(
                sampledir / "01.barcode" / f"{sample}_1.fq.gz",
                sampledir / "01.barcode" / f"{sample}_2.fq.gz",
            ),
        ),
        StepPlan(
            "02.cutadapt",
            _cutadapt_command(paths, values, str(barcode_r2)),
            outputs=(cutadapt_r2,),
        ),
        StepPlan(
            "03.star",
            _star_command(paths, values, str(cutadapt_r2)),
            outputs=(star_bam,),
        ),
        StepPlan(
            "04.featureCounts",
            [
                "celatlas_spatial",
                "rna",
                "featureCounts",
                "--outdir",
                str(sampledir / "04.featureCounts"),
                "--sample",
                sample,
                "--thread",
                str(values["featurecounts_thread"]),
                "--gtf_type",
                str(values["feature_type"]),
                "--genomeDir",
                genome,
                "--featureCounts_param",
                str(values["featurecounts_param"]),
                "--input",
                str(star_bam),
            ],
            outputs=(featurecounts_bam,),
        ),
        StepPlan(
            "05.count",
            _count_command(paths, values, str(featurecounts_bam)),
            outputs=count_outputs,
        ),
    ]

    if include_downstream:
        steps.extend(_downstream_steps(paths, values, str(count_detail)))
    return steps


def _build_reanalysis_steps(
    paths: RuntimePaths,
    values: dict[str, Any],
    *,
    include_downstream: bool,
) -> list[StepPlan]:
    if not include_downstream:
        return []
    if values["skip_binsegment"]:
        steps: list[StepPlan] = []
    else:
        steps = [_binsegment_step(paths, values, str(paths.sampledir / "05.count" / f"{paths.sample}_count_detail.txt"))]
    steps.extend(_post_binsegment_steps(paths, values))
    if not values["skip_analysis"]:
        steps.extend(_analysis_steps(paths, values))
    if not values["skip_report"]:
        steps.extend(_report_steps(paths, values))
    return steps


def _downstream_steps(paths: RuntimePaths, values: dict[str, Any], count_detail: str) -> list[StepPlan]:
    if paths.mode == "scrna":
        matrix_dir = paths.sampledir / "05.count" / f"{paths.sample}_filtered_feature_bc_matrix"
        steps = [
            StepPlan(
                "06.analysis_wrapper",
                [
                    "celatlas_spatial",
                    "rna",
                    "analysis",
                    "--outdir",
                    str(paths.sampledir / "06_analysis_wrapper"),
                    "--sample",
                    paths.sample,
                    "--thread",
                    str(values["thread"]),
                    "--genomeDir",
                    str(paths.genome_dir),
                    "--matrix_file",
                    str(matrix_dir),
                    "--assay",
                    "scrna",
                ],
                outputs=(paths.sampledir / "06_analysis_wrapper",),
            )
        ]
        steps.extend(_report_steps(paths, values))
        return steps
    steps = [_binsegment_step(paths, values, count_detail)]
    steps.extend(_post_binsegment_steps(paths, values))
    steps.extend(_analysis_steps(paths, values))
    if not values["skip_report"]:
        steps.extend(_report_steps(paths, values))
    return steps


def _barcode_command(paths: RuntimePaths, values: dict[str, Any], fq1_csv: str, fq2_csv: str) -> list[str]:
    barcode_mode = "scrna" if paths.mode == "scrna" else "strna"
    command = [
        "celatlas_spatial",
        "rna",
        "barcode",
        "--outdir",
        str(paths.sampledir / "01.barcode"),
        "--sample",
        paths.sample,
        "--thread",
        str(values["thread"]),
        "--chemistry",
        paths.chemistry,
        "--pattern",
        str(values["chemistry_pattern"]),
    ]
    if barcode_mode == "strna":
        input_dir = values["spatial_input_dir"]
        h5 = input_dir / f"{paths.sample}.barcodeToPos.h5"
        csv_path = input_dir / f"{paths.sample}_FilterBarcodes.csv"
        command.extend(["--whitelist", str(h5 if h5.exists() else csv_path)])
        bbox = input_dir / f"{paths.sample}_tissue_bbox.csv"
        if bbox.exists():
            command.extend(["--tissue-bbox", str(bbox)])
    command.extend(
        [
            "--mode",
            barcode_mode,
            "--lowNum",
            str(values["barcode_lownum"]),
            "--gzip",
            "--output_R1",
            "--resume",
        ]
    )
    if values["bbv4_strna_barcode_mismatch"] is not None:
        command.extend(["--bbv4-strna-barcode-mismatch", str(values["bbv4_strna_barcode_mismatch"])])
    if "," in fq1_csv:
        command.extend(["--max_parallel_files", str(values["max_parallel_files"])])
    command.extend(["--fq1", fq1_csv, "--fq2", fq2_csv])
    return command


def _cutadapt_command(paths: RuntimePaths, values: dict[str, Any], barcode_r2: str) -> list[str]:
    command = [
        "celatlas_spatial",
        "rna",
        "cutadapt",
        "--outdir",
        str(paths.sampledir / "02.cutadapt"),
        "--sample",
        paths.sample,
        "--thread",
        str(values["thread"]),
        "--minimum_length",
        str(values["cutadapt_min_length"]),
        "--nextseq_trim",
        str(values["cutadapt_nextseq_trim"]),
        "--gzip",
        "--overlap",
        str(values["cutadapt_overlap"]),
        "--insert",
        str(values["insert_r2"]),
    ]
    if values["cutadapt_param"]:
        command.extend(["--cutadapt_param", str(values["cutadapt_param"])])
    command.extend(["--fq", barcode_r2])
    return command


