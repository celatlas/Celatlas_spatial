def _binsegment_step(paths: RuntimePaths, values: dict[str, Any], count_detail: str) -> StepPlan:
    input_dir = values["spatial_input_dir"]
    outdir = paths.sampledir / "06.segment/01.binsegment"
    command = [
        "celatlas_spatial",
        "rna",
        "binSegment",
        "--outdir",
        str(outdir),
        "--sample",
        paths.sample,
        "--thread",
        str(values["thread"]),
        "--genomeDir",
        str(paths.genome_dir),
        "--pixel-size",
        str(values["pixel_size"]),
        "--input",
        str(input_dir),
        "--segment",
        "--model",
        str(paths.src_dir / "swin_tiny.pth"),
        "--count",
        "--count_detail",
        count_detail,
    ]
    method = get_method_module(paths.method)
    he_image = _planned_he_image(paths, input_dir) if method.requires_he_image else None
    method.extend_binsegment_command(
        command,
        sample=paths.sample,
        input_dir=input_dir,
        he_image=he_image,
        values=values,
    )
    if values["gene_mask_filter"] and paths.workflow != "SN":
        command.append("--gene-mask-filter")
    if values["fluorescence_background"]:
        command.append("--fluorescence-background")
    if values["cell_segmentation_preset"] == "dapi":
        command.append("--require-manual-he-mask")
    return StepPlan(
        "06.segment/01.binsegment",
        command,
        outputs=(outdir,),
    )


def _post_binsegment_steps(paths: RuntimePaths, values: dict[str, Any]) -> list[StepPlan]:
    bin_segment_dir = paths.sampledir / "06.segment/01.binsegment"
    steps: list[StepPlan] = []
    if values["enable_cavity_filter"]:
        cavity_outdir = bin_segment_dir / "cavity_filter"
        command = [
            "celatlas_spatial",
            "rna",
            "cavityFilter",
            "--sampledir",
            str(paths.sampledir),
            "--bin-segment-dir",
            str(bin_segment_dir),
            "--outdir",
            str(cavity_outdir),
            "--sample",
            paths.sample,
            "--bins",
            str(values["cavity_bins"]),
            "--mask-preset",
            str(values["cavity_mask_preset"]),
            "--min-component-ratio",
            str(values["cavity_min_component_ratio"]),
            "--min-hole-area",
            str(values["cavity_min_hole_area"]),
            "--close-radius",
            str(values["cavity_close_radius"]),
        ]
        if values["cavity_apply"]:
            command.append("--apply")
        if values["cavity_dry_run"]:
            command.append("--dry-run")
        if values["cavity_skip_qc_images"]:
            command.append("--skip-qc-images")
        if values["cavity_preserve_gem_support"]:
            command.append("--preserve-gem-support")
        if values["cavity_force"]:
            command.append("--force")
        steps.append(
            StepPlan(
                "06.segment/01.cavity_filter",
                command,
                outputs=(cavity_outdir,),
            )
        )

    if values["enable_stardist_cell_segment"]:
        cell_outdir = paths.sampledir / "06.segment/02.cellsegment"
        command = [
            "celatlas_spatial",
            "rna",
            "stardistCellSegment",
            "--sampledir",
            str(paths.sampledir),
            "--bin-segment-dir",
            str(bin_segment_dir),
            "--outdir",
            str(cell_outdir),
            "--sample",
            paths.sample,
            "--genomeDir",
            str(paths.genome_dir),
            "--runtime-input-dir",
            str(paths.runtime_mask_dir),
            "--model",
            str(values["stardist_model"]),
            "--prob-thresh",
            str(values["stardist_prob_thresh"]),
            "--max-dim",
            str(values["stardist_max_dim"]),
            "--scale",
            str(values["stardist_scale"]),
            "--n-tiles",
            str(values["stardist_n_tiles"]),
            "--expand-pixels",
            str(values["stardist_expand_pixels"]),
            "--min-umi",
            str(values["stardist_min_umi"]),
            "--min-genes",
            str(values["stardist_min_genes"]),
        ]
        optional_values = (
            ("--stardist-python", values["stardist_python"]),
            ("--labels", values["stardist_labels"]),
            ("--image", values["stardist_image"]),
            ("--tissue-bbox", values["stardist_tissue_bbox"]),
            ("--model-dir", values["stardist_model_dir"]),
            ("--nms-thresh", values["stardist_nms_thresh"]),
        )
        for option, value in optional_values:
            if value not in (None, ""):
                command.extend([option, str(value)])
        if values["stardist_labels"]:
            command.append("--skip-inference")
        if values["cell_segmentation_preset"] == "dapi":
            command.append("--require-registered-dapi")
            # Do not accidentally reuse a cavity mask from an older run.
            mask = bin_segment_dir / "images" / f"{paths.sample}_tissue_cut.tif"
            command.extend(["--barcode-mask", str(mask)])
        if values["stardist_skip_counts"]:
            command.append("--skip-counts")
        if values["stardist_no_label_output"]:
            command.append("--no-label-output")
        if values["stardist_tiled_inference"]:
            command.extend(
                [
                    "--tiled-inference",
                    "--tile-size",
                    str(values["stardist_tile_size"]),
                    "--tile-overlap",
                    str(values["stardist_tile_overlap"]),
                    "--tile-merge-overlap",
                    str(values["stardist_tile_merge_overlap"]),
                    "--fluorescence-channel",
                    str(values["stardist_fluorescence_channel"]),
                ]
            )
            if values["stardist_tile_cache_dir"]:
                command.extend(["--tile-cache-dir", str(values["stardist_tile_cache_dir"])])
            for rectangle in str(values["stardist_exclude_rectangle"] or "").split(";"):
                if rectangle.strip():
                    command.extend(["--exclude-rectangle", rectangle.strip()])
        steps.append(
            StepPlan(
                "06.segment/02.cellsegment",
                command,
                outputs=(cell_outdir,),
            )
        )
    return steps


