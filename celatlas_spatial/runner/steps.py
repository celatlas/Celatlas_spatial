def _get(row: dict[str, str], config: dict[str, Any], *keys: str, default: Any = None) -> Any:
    for key in keys:
        if row.get(key) not in (None, ""):
            return row[key]
    value = get_config_value(config, *keys)
    return default if value in (None, "") else value


