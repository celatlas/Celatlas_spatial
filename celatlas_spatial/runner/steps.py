def _star_value(
    row: dict[str, str],
    config: dict[str, Any],
    workflow: str,
    mode: str,
    chemistry: str,
    name: str,
) -> Any:
    if workflow == "SN":
        prefix = "sn_scrna" if mode == "scrna" else "sn_strna"
        defaults = {
            "min": 15 if mode == "scrna" else 20,
            "match_ratio": 0.15 if mode == "scrna" else 0.2,
            "score_ratio": 0.15 if mode == "scrna" else 0.2,
            "multimap": 10,
        }
        if name == "multimap":
            return _get(row, config, "sn_star_multimap", "CELATLAS_SN_STAR_MULTIMAP", default=defaults[name])
        return _get(row, config, f"{prefix}_star_{name}", f"CELATLAS_{prefix.upper()}_STAR_{name.upper()}", default=defaults[name])
    if workflow == "SX":
        defaults = {
            "min": 30 if mode == "scrna" else 25,
            "match_ratio": 0.2,
            "score_ratio": 0.2,
            "multimap": 1 if mode == "scrna" else 10,
        }
        if name == "multimap":
            return _get(row, config, "star_multimap", default=defaults[name])
        return defaults[name]
    defaults = {
        "min": 30 if mode == "scrna" else (20 if chemistry in {"BBV4", "BBV4_L9"} else 15),
        "match_ratio": 0.2,
        "score_ratio": 0.2,
        "multimap": 1 if mode == "scrna" else (10 if chemistry in {"BBV4", "BBV4_L9"} else 1),
    }
    if name == "min":
        return _get(row, config, "star_match_min", default=defaults[name])
    if name == "match_ratio":
        return _get(row, config, "star_match_ratio", default=defaults[name])
    if name == "score_ratio":
        return _get(row, config, "star_score_ratio", default=defaults[name])
    return _get(row, config, "star_multimap", default=defaults[name])


def _chemistry_pattern(chemistry: str) -> str:
    if chemistry == "BBV4":
        return "C20L15U10T18"
    if chemistry == "BBV4_L9":
        return "C20L9U10T18"
    return "C4L15C4L15C4U10T18"


def _truthy(value: Any) -> bool:
    return str(value).strip().lower() in {"1", "true", "yes", "y", "on", "enable", "enabled"}


def _normalize_step_selectors(value: str | list[str] | tuple[str, ...]) -> tuple[str, ...]:
    if isinstance(value, str):
        raw_items = value.split(",")
    else:
        raw_items = value
    return tuple(item.strip() for item in raw_items if item and item.strip())


def _selector_index(plans: list[StepPlan], selector: str | None, *, default: int) -> int:
    if not selector:
        return default
    for index, plan in enumerate(plans):
        if _step_matches(plan.name, selector.strip()):
            return index
    raise ValueError(f"Step selector not found: {selector}")


def _step_matches(step_name: str, selector: str) -> bool:
    if step_name == selector:
        return True
    if step_name.startswith(selector):
        return True
    prefix = step_name.split(".", 1)[0]
    return prefix == selector
